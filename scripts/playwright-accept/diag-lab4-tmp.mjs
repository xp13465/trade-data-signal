import { chromium } from "playwright";
const BASE = "http://127.0.0.1:8124";
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const reqs = [];
page.on("request", (r) => { const u = r.url(); if (/kelly|parts|signal/i.test(u)) reqs.push("REQ " + r.method() + " " + u.slice(0, 130)); });
page.on("response", (r) => { const u = r.url(); if (/kelly|parts|signal/i.test(u)) reqs.push("RESP " + r.status() + " " + u.slice(0, 130)); });
page.on("pageerror", (e) => reqs.push("ERR " + String(e).slice(0, 150)));
await page.goto(BASE + "/index.html", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1500);
const ob = page.locator(".onboarding-modal:not(.hidden)");
if (await ob.count()) await page.locator(".onboarding-skip").first().click().catch(() => {});
await page.waitForTimeout(300);
await page.locator('button[data-tab="lab"]').first().click({ force: true });
await page.waitForTimeout(15000);
console.log("请求记录(" + reqs.length + "):");
reqs.slice(0, 30).forEach((x) => console.log("  " + x));
const st = await page.evaluate(() => ({ err: window._labKellyLoadErr, progress: window._labKellyLoadProgress, all: window._labKellyAllReady, simErr: window._simKellyLoadErr }));
console.log("加载状态:", JSON.stringify(st));
await browser.close();
